const RAD = Math.PI / 180;
export function haversineKm(aLat, aLon, bLat, bLon) {
  const dLat = (aLat - bLat) * 111.0;
  const dLon = (aLon - bLon) * 111.0 * Math.cos(aLat * RAD);
  return Math.hypot(dLat, dLon);
}

// Test punto-en-polígono (ray casting) sobre un anillo [lat, lon].
function pointInRing(lat, lon, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const yi = ring[i][0], xi = ring[i][1];
    const yj = ring[j][0], xj = ring[j][1];
    const intersect = ((yi > lat) !== (yj > lat)) &&
      (lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}

// Nº de comuna cuyo límite real contiene el punto, o null si cae fuera de la
// ciudad. Asignación exacta para colorear/etiquetar cada hexágono.
export function comunaAt(lat, lon) {
  for (const c of COMUNA_POLYS) {
    if (pointInRing(lat, lon, c.poly)) return c.n;
  }
  return null;
}

// Comuna (objeto) más cercana a un punto, por centroide. Respaldo cuando un
// punto no cae dentro de ningún polígono (p. ej. en el borde dentado de la grilla).
export function nearestComuna(lat, lon) {
  let best = COMUNAS[0];
  let bestD = Infinity;
  for (const c of COMUNAS) {
    const d = haversineKm(lat, lon, c.lat, c.lon);
    if (d < bestD) { bestD = d; best = c; }
  }
  return { comuna: best, dist: bestD };
}
